/**
 * The seeded demo councils are the only council content that is identical for
 * every visitor, needs no API key to read, and exists nowhere else on the
 * web — so they get public, indexable permalinks. The app resolves the same
 * slugs at runtime (`/demo/:slug`, see `src/app.tsx`).
 *
 * Deliberately **no QAPage / Question structured data**: Google scopes that
 * type to pages where *people* submit answers, and these answers are model
 * output. Marking them up as a community Q&A to chase a rich result would be
 * exactly the kind of structured-data misuse that earns a manual action, so
 * these pages inherit the shell's `WebApplication` block instead.
 *
 * Answer text is excerpted rather than reproduced in full — this body is a
 * pre-mount bridge, not a second copy of the app. Less than the app shows is
 * fine; *different* from what the app shows would not be.
 */
const DEMO_DIR = fileURLToPath(
  new URL('../src/data/demo-councils', import.meta.url),
)
/** Longest answer excerpt per model in the prerendered body. */
const EXCERPT_CHARS = 700

function councilsFromFile(fileData) {
  return Array.isArray(fileData?.councils) ? fileData.councils : [fileData]
}

/** `anthropic:claude-opus-4-8` → `claude-opus-4-8 (anthropic)`. */
function modelLabel(modelId) {
  if (typeof modelId !== 'string') return 'a model'
  const [provider, ...rest] = modelId.split(':')
  const model = rest.join(':')
  return model ? `${model} (${provider})` : modelId
}

/** Strip markdown to a readable plain-text excerpt. */
function excerpt(markdown) {
  const plain = String(markdown ?? '')
    .replace(/```[\s\S]*?```/g, ' ')
    .replace(/[#*_`>|]/g, '')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/\s+/g, ' ')
    .trim()
  return plain.length > EXCERPT_CHARS
    ? `${plain.slice(0, EXCERPT_CHARS).trimEnd()}…`
    : plain
}

function demoRoute(council) {
  const turn = council.turns?.[0]
  const question = turn?.userMsg
  if (!council.title || !question) return null

  const slug = slugify(council.title)
  if (!slug) return null

  // One entry per seat: the model's *last* contribution in the turn, so a
  // consensus council shows the position it settled on rather than its
  // opening one.
  const bySeat = new Map()
  for (const event of turn.events ?? []) {
    if (event.roleType !== 'participant' && event.roleType !== 'reanswer') {
      continue
    }
    bySeat.set(event.seatId, event)
  }

  const answers = [...bySeat.values()]
    .map(
      (e) =>
        `<h3>${text(modelLabel(e.modelId))}</h3><p>${text(excerpt(e.output))}</p>`,
    )
    .join('')

  // The referee's closing word, whichever role played it.
  const closing = [...(turn.events ?? [])]
    .reverse()
    .find((e) => e.roleType === 'mediator' || e.roleType === 'judge')
  const closingHtml = closing
    ? `<h2>How it ended</h2><p>${text(
        excerpt(closing.mediator?.roundDigest?.summary ?? closing.output),
      )}</p>`
    : ''

  const lede = `A recorded Yes-Brainer council: ${bySeat.size} AI models answering one question, and where they differed. Readable without an API key.`

  return {
    path: `/demo/${slug}`,
    file: `demo/${slug}.html`,
    title: `${council.title} — a council of AI models compared`,
    description: excerpt(question).slice(0, 180),
    body:
      heroHtml(council.title, lede) +
      `<h2>The question</h2><blockquote>${text(excerpt(question))}</blockquote>` +
      `<h2>What each model said</h2>${answers}` +
      closingHtml +
      `<p class="pr__note">${text(AI_CAVEAT)}</p>` +
      HOME_LINK,
  }
}

export const DEMO_ROUTES = readdirSync(DEMO_DIR)
  .filter((f) => f.endsWith('.json'))
  .sort()
  .flatMap((f) =>
    councilsFromFile(JSON.parse(readFileSync(`${DEMO_DIR}/${f}`, 'utf8'))),
  )
  .map(demoRoute)
  .filter((r) => r !== null)

// Two demos whose titles slugify the same would collide silently and badly:
// the second would overwrite the first's HTML file, the sitemap would list
// the URL twice, and the app's `councils.find(...)` would open whichever
// sorted first — a published page showing content other than the one it was
// generated from. Cheap to detect, so detect it.
{
  const seen = new Set()
  const clashes = DEMO_ROUTES.map((r) => r.path).filter(
    (p) => seen.size === seen.add(p).size,
  )
  if (clashes.length > 0) {
    throw new Error(
      `[seo-routes] demo council titles collide on slug: ${[
        ...new Set(clashes),
      ].join(', ')} — rename one in src/data/demo-councils/.`,
    )
  }
}

/** Every path that belongs in `sitemap.xml`, in document order. */
export function sitemapPaths(extraRoutes = []) {
  return [
    HOME_ROUTE.path,
    ...CONTENT_ROUTES.map((r) => r.path),
    ...extraRoutes.map((r) => r.path),
  ]
}
