  'confidently wrong. Seeing several models agree is not evidence that they ' +
  'are right — the app shows the spread; the judgment stays yours.'

function comparisonBody(c) {
  const strengths = c.strengths.map((s) => `<li>${text(s)}</li>`).join('')
  const differences = c.differences
    .map(
      (d) =>
        `<h3>${text(d.aspect)}</h3>` +
        `<p><strong>${text(c.name)}:</strong> ${text(d.theirs)}</p>` +
        `<p><strong>Yes-Brainer:</strong> ${text(d.ours)}</p>`,
    )
    .join('')
  // The cluster's internal links have to exist *here*, not just in the React
  // component: a crawler that doesn't run JS sees only this HTML, and without
  // them each comparison is an island the hub points at but nothing points
  // back from. Mirrors what ComparisonPage renders.
  const siblings = comparisons
    .filter((o) => o.slug !== c.slug)
    .map(
      (o) =>
        `<li><a href="/vs/${o.slug}">Yes-Brainer vs ${text(o.name)}</a></li>`,
    )
    .join('')

  return (
    heroHtml(c.heading, c.lede) +
    `<h2>What ${text(c.name)} does well</h2><ul>${strengths}</ul>` +
    `<h2>Where they differ</h2>${differences}` +
    `<h2>Which to pick</h2>` +
    `<p><strong>Pick ${text(c.name)} if:</strong> ${text(c.pickTheirs)}</p>` +
    `<p><strong>Pick Yes-Brainer if:</strong> ${text(c.pickOurs)}</p>` +
    `<h2>Other comparisons</h2>` +
    `<p><a href="/vs">How Yes-Brainer compares</a> — the category-level view: ` +
    `hosted council products, the open-source llm-council forks, and ` +
    `multi-model chat aggregators.</p>` +
    `<ul>${siblings}</ul>` +
    `<p class="pr__note">${text(AI_CAVEAT)}</p>` +
    HOME_LINK
  )
}

