/** `<h1>` + lede, the opening of every prerendered body. */
function heroHtml(title, lede) {
  return `<h1>${text(title)}</h1><p class="pr__lede">${text(lede)}</p>`
}

/**
 * Every prerendered body ends with a way onward. Without it these pages are
 * dead ends for the two audiences that only ever see this HTML: a crawler
 * that doesn't run JS (no path to the rest of the site) and a visitor whose
 * JS hasn't loaded yet (no path to the app). One link fixes both.
 */
const HOME_LINK =
  '<p class="pr__note"><a href="/">Yes-Brainer</a> — ask several AI models ' +
  'one question and see where they disagree. Free and open source; no ' +
  'account, and you bring your own API keys.</p>'

