/**
 * The SEO route manifest — the single source of truth for **which paths get a
 * prerendered HTML file** and **what goes into `sitemap.xml`**. Consumed by
 * `scripts/prerender.mjs` at build time; nothing imports it at runtime.
 *
 * Why a manifest at all: the app is a client-rendered SPA, so a crawler that
 * doesn't execute JS sees one shell for every URL. Vite emits a single
 * `index.html`; this manifest is the list of routes that deserve their own
 * file with their own `<title>`, description, canonical and OG/Twitter tags —
 * plus, for content routes, real text inside `#root` so a non-JS crawler
 * (most AI answer engines, most link-preview bots) has something to read.
 * `createRoot` clears `#root`'s children on mount, so that prerendered text
 * is replaced by the real app the moment React boots — same content, no
 * hydration contract, nothing hidden from users that a crawler can see.
 *
 * **Every `path` here must also be a real route in the app** (see
 * `src/hooks/use-app-route.ts`). A prerendered file without a matching client
 * route would render the shell's fallback after React mounts — a visible
 * content swap. Adding a page means touching both.
 *
 * The `/vs/*` entries are derived from `src/models/comparisons.json`, which
 * the app reads too, so the page and its prerendered copy cannot disagree.
 *
 * Per-user routes (`/council/:id`, `/settings`) are deliberately absent: they
 * are client state, not documents. They fall through to `dist/404.html`,
 * which Pages serves with an HTTP 404 status so crawlers skip them.
 */

